import {responseProtectionReason,queryOperation,ignorableQueryFailure,waitForDialogToClear} from './protection.mjs';
import {extractCandidates} from '../profile-email-finder/finder.mjs';
export function bioEmails(biography){
 return extractCandidates({url:'https://www.instagram.com/profile/',blocks:[{text:biography,source:'profile_bio'}]}).emails.filter(e=>e.status==='confirmed_public').map(e=>e.email);
}
export function normalizeBioLinks(links){
 const result=[],seen=new Set();
 for(const link of links){
  if(!link||typeof link!=='object')continue;
  const rawUrl=link.url||link.href;let url;
  try{
   url=new URL(rawUrl);
   if(url.hostname==='l.instagram.com')url=new URL(url.searchParams.get('u'));
  }catch{continue;}
  if(!['http:','https:'].includes(url.protocol)||seen.has(url.href))continue;
  seen.add(url.href);result.push({title:link.title||link.text||'',url:url.href,rawUrl});
 }
 return result;
}
export function parseProfilePayload(payload,username){
 if(!payload||typeof payload!=='object')return null;
 if(typeof payload.username==='string'&&payload.username.toLowerCase()===username.toLowerCase()&&typeof payload.biography==='string'){
  const rawLinks=[...(Array.isArray(payload.bio_links)?payload.bio_links:[]),...(payload.external_url?[{url:payload.external_url}]:[])],links=normalizeBioLinks(rawLinks);
  return {authorId:payload.pk==null?payload.id==null?null:String(payload.id):String(payload.pk),username:payload.username,biography:payload.biography,emails:bioEmails(payload.biography),links,linksComplete:Array.isArray(payload.bio_links)&&rawLinks.every(link=>normalizeBioLinks([link]).length===1),source:'instagram_native_profile_response'};
 }
 for(const value of Object.values(payload)){const found=parseProfilePayload(value,username);if(found)return found;}
 return null;
}
export function mergeVisibleProfile(cached,dom,username){
 if(dom?.username?.toLowerCase()!==username.toLowerCase()||typeof dom.biography!=='string'||dom.truncated)return cached;
 const links=normalizeBioLinks([...(cached?.links||[]),...(dom.links||[])]);
 return {...cached,username,biography:dom.biography,emails:bioEmails(dom.biography),links,linksComplete:!dom.hasMultiLinks||cached?.linksComplete===true&&links.length===cached.links.length,source:'instagram_profile_dom',freshness:'loaded_page_not_revalidated'};
}

// Observe responses generated by normal navigation; never replay a private endpoint.
async function profileResponses(page,username,warnings){
 let found=null;
 const events=await page.events();
 for(const event of events){
  if(event.method!=='Network.responseReceived')continue;
  const response=event.params.response;let url;try{url=new URL(response.url);}catch{continue;}
  if(url.hostname!=='www.instagram.com'||!/^\/(api\/|graphql\/)/.test(url.pathname))continue;
  if([401,403,429].includes(response.status))throw new Error('instagram_access_stopped_'+response.status);
  let body;try{const raw=await page.cdp('Network.getResponseBody',{requestId:event.params.requestId});body=raw.base64Encoded?Buffer.from(raw.body,'base64').toString():raw.body;}catch{continue;}
  for(const line of body.replace(/^for\s*\(;;\);/,'').split('\n')){
   let payload;try{payload=JSON.parse(line);}catch{continue;}
   const operation=queryOperation(events,event.params.requestId);
   if(ignorableQueryFailure(operation,response.status,payload)){warnings.push({operation,reason:responseProtectionReason(payload),ignored:true});continue;}
   const protection=responseProtectionReason(payload);if(protection)throw new Error(protection);
   const profile=parseProfilePayload(payload,username);if(profile)found=profile;
  }
 }
 return found;
}

export async function readProfile({page,username,navigate=true,stopOnBioEmail=false}){
 if(typeof username!=='string'||!/^[A-Za-z0-9._]{1,30}$/.test(username))throw new Error('invalid_instagram_username');
 const base={username,profileUrl:'https://www.instagram.com/'+username+'/',status:'unknown',biography:null,emails:null,links:[],linksComplete:false,warnings:[]};
 let opened=false,controlLost=false,linksInspected=false;
 try{
  if(await page.evaluate(()=>!!document.querySelector('[role="dialog"]'))&&!await waitForDialogToClear(page))return {...base,reason:'existing_dialog'};
  await page.cdp('Network.enable',{maxPostDataSize:65536});await page.events();
  if(navigate&&(await page.url())!==base.profileUrl)await page.goto(base.profileUrl);
  const current=new URL(await page.url());
  if(/^\/(accounts\/login|challenge|checkpoint)(\/|$)/.test(current.pathname))return {...base,status:'paused',reason:'instagram_login_or_challenge'};
  if(current.hostname!=='www.instagram.com'||current.pathname.toLowerCase()!=='/'+username.toLowerCase()+'/')return {...base,reason:'profile_url_mismatch'};
  await page.waitForSelector('main header',{timeout:15000});await page.waitForTimeout(1000);
  const heading=await page.evaluate(()=>document.querySelector('main header h2,main header h1')?.textContent?.trim());
  if(heading?.toLowerCase()!==username.toLowerCase())return {...base,reason:'profile_identity_mismatch'};
  let data=null;
  // Use the already-loaded document before considering any network failure.
  const scripts=await page.evaluate(()=>[...document.querySelectorAll('script[type="application/json"]')].map(s=>s.textContent))||[];
  for(const script of scripts){let payload;try{payload=JSON.parse(script);}catch{continue;}const parsed=parseProfilePayload(payload,username);if(parsed){data={...parsed,source:'instagram_profile_hydration',freshness:'loaded_page_not_revalidated'};break;}}
  const dom=await page.evaluate(()=>{
   const header=document.querySelector('main header');
   return {username:header?.querySelector('h2,h1')?.textContent?.trim(),biography:[...header?.querySelectorAll('[role="button"]')||[]].find(e=>e.style.display==='inline')?.innerText,truncated:[...header?.querySelectorAll('[role="button"]')||[]].some(e=>/^(更多|more)$/i.test(e.innerText?.trim())),hasMultiLinks:[...header?.querySelectorAll('[role="button"],button')||[]].some(e=>/另外\s*\d+\s*条|and\s+\d+\s+more/i.test(e.textContent)&&!!e.querySelector('svg[aria-label="链接图标"],svg[aria-label="Link icon"]')),links:[...header?.querySelectorAll('a[href^="https://l.instagram.com/"]')||[]].map(a=>({url:a.href,title:a.innerText}))};
  });
  data=mergeVisibleProfile(data,dom,username);
  if(!data)data=await profileResponses(page,username,base.warnings);
  if(stopOnBioEmail&&data?.emails?.length)return {...base,...data,status:'observed',capturedAt:new Date().toISOString()};
  linksInspected=true;
  const moreLinks=await page.evaluate(()=>{
   const button=[...document.querySelectorAll('main header [role="button"],main header button')].find(e=>e.querySelector('svg[aria-label="链接图标"],svg[aria-label="Link icon"]')&&/另外\s*\d+\s*条|and\s+\d+\s+more/i.test(e.textContent));
   if(!button)return null;button.setAttribute('data-creator-profile-links','');
   return {expectedCount:1+Number(button.textContent.match(/另外\s*(\d+)\s*条|and\s+(\d+)\s+more/i).slice(1).find(x=>x!==undefined))};
  });
  if(moreLinks&&(!data?.linksComplete||data.links.length!==moreLinks.expectedCount)){
   await page.click('[data-creator-profile-links]');opened=true;
   await page.waitForSelector('[role="dialog"]',{timeout:10000});
   try{await page.waitForFunction(expected=>[...document.querySelectorAll('[role="dialog"]')].some(d=>/^(链接|Links)\s*/i.test(d.innerText?.trimStart()||'')&&d.querySelectorAll('a[href]').length>=expected),moreLinks.expectedCount,{timeout:8000});}
   catch(error){if(!/timeout/i.test(error.message))throw error;}
   const dialog=await page.evaluate(()=>{
    const d=[...document.querySelectorAll('[role="dialog"]')].find(e=>/^(链接|Links)\s*/i.test(e.innerText));
    if(!d)return null;d.setAttribute('data-creator-profile-dialog','');
    return [...d.querySelectorAll('a[href]')].map(a=>({title:a.innerText,url:a.href}));
   });
   if(!dialog)return {...base,...data,status:'partial',reason:'links_dialog_identity_unknown'};
   const links=normalizeBioLinks(dialog);
   const linksComplete=links.length===dialog.length&&links.length===moreLinks.expectedCount;
   if(data)data={...data,links,linksComplete,linksSource:'instagram_native_links_dialog'};
   else data={links,linksComplete,linksSource:'instagram_native_links_dialog'};
  }
  // An unread biography must never be reported as an empty one or as no email.
  if(!data)return {...base,reason:'native_profile_data_not_observed'};
  const complete=typeof data.biography==='string'&&data.linksComplete;
  return {...base,...data,status:complete?'observed':'partial',capturedAt:new Date().toISOString(),...complete?{}:{reason:'profile_fields_incomplete'}};
 }catch(error){
  if(error.pause||error.storageFailure){controlLost=true;throw error;}
  if(/Control of this task space|delegat|ownership/i.test(error.message)){controlLost=true;throw error;}
  return {...base,status:/instagram_access_stopped_|instagram_login_or_challenge/.test(error.message)?'paused':'unknown',reason:error.message};
 }finally{
  if(!controlLost){
   if(opened){
    const close=await page.evaluate(()=>{
     const d=document.querySelector('[data-creator-profile-dialog]');const b=d?.querySelector('[aria-label="关闭"],[aria-label="Close"]')?.closest('button,[role="button"]');
     if(!b)return false;b.setAttribute('data-creator-profile-close','');return true;
    });
    if(close){await page.click('[data-creator-profile-close]');await page.waitForFunction(()=>!document.querySelector('[data-creator-profile-dialog]'),undefined,{timeout:5000});}
   }
   if(linksInspected)await page.evaluate(()=>document.querySelectorAll('[data-creator-profile-links]').forEach(e=>e.removeAttribute('data-creator-profile-links')));
  }
 }
}
